export async function initRoles(client: Client) {
  const { GuildId } = getConfig();
  const guild = await client.guilds.fetch(GuildId);

  if (!guild) {
    logger.error("Could not find the target guild for roles!");
    return;
  }

  const roles = await guild.roles.fetch();

  // Reset and Populate the ROLES variable
  ROLES = {};
  roles.forEach((role) => {
    // Formats names to "ADMIN_ROLE" style for easier coding
    const cleanName = role.name.toUpperCase().replace(/\s+/g, "_");
    ROLES[cleanName] = role.id;
  });

  logger.info(`loaded ${Object.keys(ROLES).length} roles.`);
}
